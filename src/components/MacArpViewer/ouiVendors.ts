/**
 * Normalizes a MAC address to uppercase hex without separators.
 *
 * Handles formats: "aa:bb:cc:dd:ee:ff", "aa-bb-cc-dd-ee-ff",
 * "aabb.ccdd.eeff", "AABBCCDDEEFF"
 */
export function normalizeMac(mac: string): string {
  return mac.replace(/[:\-.\s]/g, "").toUpperCase();
}

/**
 * Looks up the vendor for a MAC address using the OUI database.
 *
 * Returns the vendor name or "Unknown" if not found.
 */
export function lookupVendor(mac: string): string {
  const normalized = normalizeMac(mac);
  if (normalized.length < 6) return "Unknown";
  const oui = normalized.substring(0, 6);
  return OUI_VENDORS[oui] || "Unknown";
}
